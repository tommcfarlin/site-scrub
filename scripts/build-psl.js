// @ts-check
// Build psl-data.js from a local copy of the public suffix list.
// Usage: node scripts/build-psl.js <path to public_suffix_list.dat>
// This script makes no network call. Download the list by hand from
// https://publicsuffix.org/list/public_suffix_list.dat first.
import { readFileSync, writeFileSync } from "node:fs";
import { domainToASCII } from "node:url";
import { fileURLToPath } from "node:url";

const input = process.argv[2];
if (!input) {
  console.error("Usage: node scripts/build-psl.js <public_suffix_list.dat>");
  process.exit(1);
}

/** @type {string[]} */ const exact = [];
/** @type {string[]} */ const wildcard = [];
/** @type {string[]} */ const exception = [];

// Both the ICANN and the private sections are included.
for (const raw of readFileSync(input, "utf8").split(/\r?\n/)) {
  const line = raw.trim().split(/\s+/)[0];
  if (!line || line.startsWith("//")) continue;
  if (line.startsWith("!")) {
    exception.push(domainToASCII(line.slice(1)));
  } else if (line.startsWith("*.")) {
    wildcard.push(domainToASCII(line.slice(2)));
  } else {
    exact.push(domainToASCII(line));
  }
}

const clean = (/** @type {string[]} */ a) => [...new Set(a.filter(Boolean))].sort();
const rules = { exact: clean(exact), wildcard: clean(wildcard), exception: clean(exception) };

const out =
  "// @ts-check\n" +
  "// GENERATED by scripts/build-psl.js from the public suffix list.\n" +
  "// Do not edit by hand. Re-run the script to update it.\n" +
  "/** @type {{ exact: string[], wildcard: string[], exception: string[] }} */\n" +
  "export const RULES = " + JSON.stringify(rules) + ";\n";
writeFileSync(fileURLToPath(new URL("../psl-data.js", import.meta.url)), out);
console.log(`exact ${rules.exact.length}, wildcard ${rules.wildcard.length}, exception ${rules.exception.length}`);
